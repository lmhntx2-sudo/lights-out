export function driverCode(last) {
  const parts = String(last)
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/^(al-|de |van den |van der |van |di |da |le )/i, '')
    .replace(/[^a-zA-Z]/g, '');
  return (parts.slice(0, 3) || 'XXX').toUpperCase().padEnd(3, 'X');
}
